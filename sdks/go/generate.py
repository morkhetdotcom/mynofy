"""Development-only generator. No protoc, Python or gRPC needed by Go consumers."""
from pathlib import Path
import json
import os
import subprocess
import sys

root = Path(__file__).resolve().parents[2]
plugin = os.environ.get('PROTOC_GEN_GO', 'protoc-gen-go')
subprocess.run([sys.executable, '-m', 'grpc_tools.protoc',
                '-I' + str(root / 'protocol/protobuf'),
                '--plugin=protoc-gen-go=' + plugin,
                '--go_out=' + str(root / 'sdks/go/protocol'),
                '--go_opt=paths=source_relative',
                '--go_opt=Mmynofy.proto=mynofy.local/sdk/go/protocol',
                str(root / 'protocol/protobuf/mynofy.proto')], check=True)
catalog = json.loads((root / 'protocol/catalogs/mynofy-v1.json').read_text())
lines = ['// Code generated by sdks/go/generate.py; DO NOT EDIT.', 'package mynofy']
for name, key in [('Category', 'categories'), ('Action', 'actions'), ('Status', 'statuses')]:
    ids = ','.join(str(v['id']) for v in catalog[key])
    lines += [f'func valid{name}(id uint32) bool {{switch id {{case {ids}:return true;default:return false}}}}']
(root / 'sdks/go/catalog_generated.go').write_text('\n'.join(lines) + '\n')
subprocess.run([os.environ.get('GOFMT', 'gofmt'), '-w',
                str(root / 'sdks/go/protocol/mynofy.pb.go'),
                str(root / 'sdks/go/catalog_generated.go')], check=True)
