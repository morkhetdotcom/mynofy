"""Generate Java bindings/catalog from shared sources; development tool only."""
import json
import os
from pathlib import Path
import subprocess
import tempfile

root = Path(__file__).resolve().parents[2]
output = root / 'sdks/java/src/main/java'
source = (root / 'protocol/protobuf/mynofy.proto').read_text()
# Java-specific output options do not change messages or wire fields.
source = source.replace('package mynofy.v1;', 'package mynofy.v1;\noption java_package = "dev.mynofy.protocol";\noption java_outer_classname = "Wire";')
with tempfile.TemporaryDirectory(prefix='mynofy-java-proto-') as temporary:
    schema = Path(temporary) / 'mynofy.proto'
    schema.write_text(source)
    subprocess.run([os.environ.get('PROTOC', 'protoc'), '-I' + temporary,
                    '--java_out=' + str(output), str(schema)], check=True)
catalog = json.loads((root / 'protocol/catalogs/mynofy-v1.json').read_text())
lines = ['// Generated by sdks/java/generate.py; DO NOT EDIT.', 'package dev.mynofy;',
         'final class CatalogIds {', '    private CatalogIds() {}']
for name, key in [('category', 'categories'), ('action', 'actions'), ('status', 'statuses')]:
    ids = ', '.join(str(v['id']) for v in catalog[key])
    lines += [f'    static boolean {name}(int id) {{',
              f'        return switch (id) {{ case {ids} -> true; default -> false; }};', '    }']
lines += ['}']
(output / 'dev/mynofy/CatalogIds.java').write_text('\n'.join(lines) + '\n')
