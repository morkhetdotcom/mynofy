"""Regenerate bindings from the existing .proto; compiler is a dev-only dependency."""
from pathlib import Path
import subprocess
import sys

root = Path(__file__).resolve().parents[2]
subprocess.run([sys.executable, '-m', 'grpc_tools.protoc',
                '-I' + str(root / 'protocol/protobuf'),
                '--python_out=' + str(root / 'sdks/python/src/mynofy'),
                str(root / 'protocol/protobuf/mynofy.proto')], check=True)
# Validation tables are generated from the same authoritative catalog as Rust.
import json
catalog = json.loads((root / 'protocol/catalogs/mynofy-v1.json').read_text())
lines = ['# Generated by sdks/python/generate.py; do not edit by hand.']
for field in ['categories', 'actions', 'statuses']:
    lines.append(field.upper() + ' = frozenset(' + repr([v['id'] for v in catalog[field]]) + ')')
(root / 'sdks/python/src/mynofy/_catalog.py').write_text('\n'.join(lines) + '\n')
